const ALL: DeskArticle[] = [...ISSUES, ...GUIDES, ...SEASONS];

export const findArticle = (id: string): DeskArticle | undefined =>
  ALL.find((item) => item.id === id);

export const findCountry = (code: string): CountryDesk | undefined =>
  COUNTRIES.find((item) => item.code.toLowerCase() === code.toLowerCase());

export const guidesByTopic = (topic: DeskTopic | null): DeskArticle[] =>
  topic ? GUIDES.filter((item) => item.topic === topic) : GUIDES;

export const relatedArticles = (current: DeskArticle): DeskArticle[] => {
  if (current.kind === 'season' && current.month) {
    const neighbor = new Set([
      current.month === 1 ? 12 : current.month - 1,
      current.month === 12 ? 1 : current.month + 1,
    ]);
    return SEASONS.filter((item) => item.month && neighbor.has(item.month));
  }
  return ALL.filter(
    (item) =>
      item.id !== current.id &&
      item.topic === current.topic &&
      item.kind !== 'season',
  ).slice(0, 3);
};

export const articlesForCountry = (country: CountryDesk): DeskArticle[] =>
  country.guideIds
    .map((id) => findArticle(id))
    .filter((item): item is DeskArticle => Boolean(item));
